R=8300
def state(nN2, T, Pv, nE=Rational(5,100), V=5):
    VA = nN2*R*T/Pv; VB = V-VA; ng = Pv*VB/(R*T)
    return VA, ng, nE-ng
VA, ng, liq = state(Rational(1,100), 300, 9000)
ok(sig(VA,2)==2.8 and liq>0, f'(1) {float(VA):.3f}'); ok(sig(liq,2)==0.042, f'(2) {float(liq):.4f}')
VA3, ng3, liq3 = state(Rational(15,1000), 300, 9000)
ok(sig(liq3,2)==0.047 and liq3>liq and VA3<5, f'(3) {float(liq3):.4f}')
VA4, ng4, liq4 = state(Rational(1,100), 320, 26000); ok(liq4>0, f'(4) liquid remains {float(liq4):.4f}')
Pall = Rational(6,100)*R*340/5; ok(Pall < 64000, f'(5) all vapor {float(Pall):.0f}')
ok(sig(5*Rational(1,6),2)==0.83, '(5) 0.83')

finish()
