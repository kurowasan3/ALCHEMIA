def comp(V1, V2, c=0.100, vol=20.0):
    a = c*min(V1, V2); b = c*abs(V1 - V2)
    return ('NaOH' if V1 > V2 else 'NaHCO3' if V1 < V2 else None), a/vol, b/vol
