mass = {'H2': e/2*2, 'CO': e/2*28, 'CH4': e/8*16}
co2 = {'H2': 0, 'CO': e/2, 'CH4': e/8}
print({k: float(v) for k,v in mass.items()}, co2)
assert [sig(float(mass[k]),2) for k in ('H2','CH4','CO')] == [2.7, 5.3, 37]
assert sorted(mass, key=lambda k: mass[k]) == ['H2','CH4','CO'] and sorted(co2, key=lambda k: co2[k]) == ['H2','CH4','CO']

